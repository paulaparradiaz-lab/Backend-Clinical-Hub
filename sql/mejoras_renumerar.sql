-- Paula pidió este orden. Solo cambia el número (id) de cada mejora
-- y, con él, el de sus enlaces, personas e historial. No borra nada.
--
--   Insuficiencia cardíaca descompensada   5 → 1
--   Insuficiencia cardíaca crónica         4 → 2
